// **เจ้าของบอก 2026-11-21: เอาแค่หัวน้องก็พอ** → หน้าทำข้อแสดงเฉพาะหัว (ตัดกรอบ T.HEAD ด้านล่างจากเฟรม 48×48) ท่าจึงต้องอ่านออกจากหน้าอย่างเดียว
// โหลดหลัง js/pixelcat.js แล้วเพิ่มท่าร่างลง PixelCat._t.POSES (ตัวช่วยใน _t.lib คือฟังก์ชันชุดเดียวกับในไฟล์นั้น)
// · yay ยิ้มตาปิดเด้ง (ตอบถูก): หัวเด้งขึ้นลง ตา ⌒ ⌒ ปากอ้าเห็นลิ้น แก้มแดง ประกายรอบหัว
// · nod พยักหน้าให้กำลังใจ (ตอบผิด): พยักหน้าช้าๆ สองที ตาปิดยิ้มตอนก้ม (ไม่ใช้ท่าเศร้า: ตอบผิดไม่ใช่เรื่องผิด · รายงานบทพูด)
// · ร่างแรกมีท่าชูอุ้งเท้าไฮไฟว์ทั้งตัว แต่เจ้าของเลือกแสดงแค่หัว จึงตัดออก
// เลือกแล้วให้ย้ายเข้า POSES และ INFO ใน js/pixelcat.js (รองรับ 9 ลายขน ผ้าพันคอ โบว์ สองโหมด ตามกติกาเครื่องประดับ)
(function () {
  const T = PixelCat._t, L = T.lib, { sitCat, put, bean, eyeHappy, mouth, blush, EYE, NOSE } = L;
  const TONGUE = '#ff8aa0', SPARK = '#f2c14e';
  const spark = (a, x, y) => put(a, x, y, [[1, 0], [0, 1], [1, 1], [2, 1], [1, 2]], SPARK);
  // พยักหน้า: หัวก้มลงแล้วเงยสองครั้ง ตาปิดยิ้มตอนก้ม (เหมือนบอกว่า "ไม่เป็นไรนะ")
  const ND = [{ hy: 0, e: 0 }, { hy: 1.6, e: 1 }, { hy: .4, e: 0 }, { hy: 1.6, e: 1 }];
  Object.assign(T.POSES, {
    yay: f => { const dy = [0, -1.2, -2, -1][f]; return sitCat({ dy, ear: -.1,
      face: (a, hx, hy) => { eyeHappy(a, 15.6, hy + 1); eyeHappy(a, 26.6, hy + 1); a.push([24, hy + 3.6, NOSE]); put(a, 22, hy + 4.6, [[0, 0], [1, 0], [2, 0], [3, 0]], EYE); put(a, 23, hy + 5.6, [[0, 0], [1, 0]], TONGUE); blush(a, 12.6, hy + 3.8); blush(a, 32.4, hy + 3.8) },
      fx: (a, by) => { if (f) (f % 2 ? [[8, 9], [37, 5]] : [[37, 11], [9, 4]]).forEach(([x, y]) => spark(a, x, y + by * .5)) } }) },
    nod: f => { const N = ND[f]; return sitCat({ hy: N.hy, ear: .22, tilt: .05,
      face: (a, hx, hy) => { if (N.e) { eyeHappy(a, 15.8, hy + 1.6); eyeHappy(a, 26.8, hy + 1.6) } else { bean(a, 17.6, hy + 1.6, 3); bean(a, 28.6, hy + 1.6, 3) } a.push([24, hy + 3.8, NOSE]); mouth(a, 22, hy + 4.8); blush(a, 12.6, hy + 3.8); blush(a, 32.4, hy + 3.8) } }) } });
  T.DRAFT_DUR = { yay: [140, 200, 260, 200], nod: [380, 420, 300, 520] };
  T.HEAD = [6, 1, 36, 32]; // กรอบตัดเหลือแค่หัว: x, y, กว้าง, สูง ในเฟรม 48×48
})();
